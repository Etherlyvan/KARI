import pg from 'pg';

// Run only in the one-off migration container, using its admin DATABASE_URL.
// Passwords are read from environment and never passed as CLI arguments or printed.
let client;
try {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('Database configuration missing.');
  const url = new URL(connectionString);
  if (!['postgres:', 'postgresql:'].includes(url.protocol) || url.pathname !== '/kari' || url.username !== 'kari_admin') {
    throw new Error('Use only the configured migration admin and dedicated kari database.');
  }
  client = new pg.Client({ connectionString, connectionTimeoutMillis: 5000, statement_timeout: 10000 });
  await client.connect();
  await client.query('BEGIN');
  await client.query("SET LOCAL lock_timeout = '5s'");
  await client.query('ALTER ROLE kari_app NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS');
  await client.query('REVOKE ALL ON DATABASE kari FROM PUBLIC');
  await client.query('REVOKE CREATE ON SCHEMA public FROM PUBLIC');
  await client.query('REVOKE ALL ON DATABASE kari FROM kari_app');
  await client.query('GRANT CONNECT ON DATABASE kari TO kari_app');
  await client.query('REVOKE ALL ON SCHEMA public FROM kari_app');
  await client.query('GRANT USAGE ON SCHEMA public TO kari_app');
  await client.query('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM kari_app');
  await client.query('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM kari_app');
  // UUID identifiers are generated by Prisma; no sequence or migration-table access is needed.
  await client.query('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE "SpendBucket", "SpendReservation", "FinancialState", "Note", "Reminder" TO kari_app');
  await client.query('COMMIT');
  console.log('Application database grants applied.');
} catch {
  try { await client?.query('ROLLBACK'); } catch { /* keep diagnostic free of connection strings */ }
  console.error('Application database grants failed. Check admin configuration, initialization and migrations; credentials are omitted.');
  process.exitCode = 1;
} finally {
  try { await client?.end(); } catch { process.exitCode = 1; }
}
